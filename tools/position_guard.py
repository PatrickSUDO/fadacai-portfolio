def rev_30d(fund, sym):
    """(up, down) 30 日 revision 筆數；curr_q 優先，缺則 curr_fy。抓不到 → (None, None)。"""
    fe = ((fund.get(sym) or {}).get("snapshot") or {}).get("forward_estimates") or {}
    for k in ("curr_q", "curr_fy", "next_fy"):
        b = fe.get(k) or {}
        if b.get("revisions_up_30d") is not None or b.get("revisions_down_30d") is not None:
            return float(b.get("revisions_up_30d") or 0), float(b.get("revisions_down_30d") or 0)
    return None, None


def market_frame(symbols):
    """一次抓 7 個月日線 → {sym: {last, sma20, sma50, high20, ret90}}；SPY 一併抓作 RS 基準。失敗回 {}。"""
    try:
        import yfinance as yf
        syms = sorted(set(symbols) | {"SPY", "IGV", "SMH"})
        px = yf.download(syms, period="14mo", auto_adjust=True, progress=False)["Close"]  # 14 個月供 EMA200 收斂
        out = {}
        for s in syms:
            if s not in px:
                continue
            c = px[s].dropna()
            if len(c) < 60:
                continue
            out[s] = {"last": float(c.iloc[-1]), "sma20": float(c.tail(20).mean()), "sma50": float(c.tail(50).mean()),
                      "ema200": float(c.ewm(span=200, adjust=False).mean().iloc[-1]) if len(c) >= 120 else None,
                      # EMA50 5 日斜率（%）：兩線上子集內 ≥2% → 20 日 4.78%/61.5% vs 3.73%/59.7%；進排序不進閘門（ma-filter-evidence D）
                      "ema50_slope5_pct": float((lambda e: (e.iloc[-1] / e.iloc[-6] - 1) * 100)(c.ewm(span=50, adjust=False).mean())) if len(c) >= 60 else None,
                      # 布林帶寬擠壓：20 日帶寬在近 120 日最低 20%（ma-filter-evidence E：擠壓且兩線上 20 日 4.73%/63.3% vs 3.58%/57.6%）
                      "bb_squeeze": bool((lambda bw: bw.iloc[-1] <= bw.tail(120).quantile(0.2))((c.rolling(20).std() * 4 / c.rolling(20).mean()).dropna())) if len(c) >= 140 else False,
                      "high20": float(c.tail(20).max()), "high60": float(c.tail(60).max()), "high10": float(c.tail(10).max()),
                      "ret90": float(c.iloc[-1] / c.iloc[-min(63, len(c))] - 1)}
        return out
    except Exception as e:  # noqa: BLE001
        print(f"[warn] market_frame failed: {e}", file=sys.stderr)
        return {}


