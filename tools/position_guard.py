def render_plan(table_md):
    text = PLAN.read_text()
    block = f"{PLAN_BEGIN}\n{table_md}\n{PLAN_END}"
    if PLAN_BEGIN in text and PLAN_END in text:
        pre = text[: text.index(PLAN_BEGIN)]
        post = text[text.index(PLAN_END) + len(PLAN_END):]
        PLAN.write_text(pre + block + post)
    else:
        PLAN.write_text(text.rstrip() + "\n\n## 持倉狀態（自動生成）\n\n" + block + "\n")
    return True


